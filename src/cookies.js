// Netscape cookies.txt <-> Playwright cookies, plus a Cookie header for plain fetches.
import fs from 'node:fs';

export function readCookieFile(file) {
  if (!file) return [];
  const cookies = [];
  for (let line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    let httpOnly = false;
    if (line.startsWith('#HttpOnly_')) {
      httpOnly = true;
      line = line.slice('#HttpOnly_'.length);
    }
    if (!line.trim() || line.startsWith('#')) continue;
    const [domain, , path, secure, expires, name, ...rest] = line.split('\t');
    if (!name) continue;
    cookies.push({
      name,
      value: rest.join('\t'),
      domain,
      path: path || '/',
      secure: secure === 'TRUE',
      httpOnly,
      expires: Number(expires) > 0 ? Number(expires) : -1,
    });
  }
  return cookies;
}

export function writeCookieFile(file, cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by vidgrab'];
  for (const c of cookies) {
    const domain = c.httpOnly ? `#HttpOnly_${c.domain}` : c.domain;
    const sub = c.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expires = c.expires > 0 ? Math.floor(c.expires) : 0;
    lines.push([domain, sub, c.path || '/', c.secure ? 'TRUE' : 'FALSE', expires, c.name, c.value].join('\t'));
  }
  fs.writeFileSync(file, `${lines.join('\n')}\n`);
}

export function cookieHeader(cookies, url) {
  let u;
  try {
    u = new URL(url);
  } catch {
    return '';
  }
  const host = u.hostname;
  return cookies
    .filter((c) => {
      const d = c.domain.replace(/^\./, '');
      return (host === d || host.endsWith(`.${d}`)) && u.pathname.startsWith(c.path || '/');
    })
    .map((c) => `${c.name}=${c.value}`)
    .join('; ');
}
